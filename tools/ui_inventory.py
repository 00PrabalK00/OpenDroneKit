"""Render docs/ui/INVENTORY.md from docs/ui/inventory.json.

The JSON is the source of truth: every control the classic and cockpit UIs can reach,
its Api methods, and its home in the v1 interface. The Markdown is generated from it so
the two cannot disagree.

    python tools/ui_inventory.py            # print the Markdown
    python tools/ui_inventory.py --write    # rewrite docs/ui/INVENTORY.md
    python tools/ui_inventory.py --check    # exit 1 if INVENTORY.md is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = REPO_ROOT / "docs" / "ui" / "inventory.json"
MD_PATH = REPO_ROOT / "docs" / "ui" / "INVENTORY.md"

TITLES = {
    "shell": "Global shell (every workspace)", "home": "Home", "plan": "Plan", "fly": "Fly",
    "process": "Process", "analyse": "Analyse", "review": "Review", "fleet": "Fleet",
    "report": "Report", "settings": "Settings",
}


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _codes(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items) if items else "—"


def render(doc: dict) -> str:
    rows = doc["rows"]
    out: list[str] = []
    w = out.append
    w("# v1 interface inventory")
    w("")
    w("Generated by `python tools/ui_inventory.py --write` from `docs/ui/inventory.json`. "
      "Do not edit by hand: edit the JSON and regenerate.")
    w("")
    w(f"Source: {doc['source']}.")
    w("")
    w("This is the \"nothing dropped\" ledger for the rebuild. `tests/test_ui_v1_inventory.py` "
      "fails if a native menu item, a cockpit `ACTIONS` key or a public `Api` method has no row "
      "here, or if a row has no new home.")
    w("")
    counts = Counter(r["workspace"] for r in rows)
    kinds = Counter(r["placement"] for r in rows)
    w("| Measure | Count |")
    w("|---|---:|")
    w(f"| Rows | {len(rows)} |")
    w(f"| Native menu items covered | {len(doc['menu'])} |")
    w(f"| Cockpit ACTIONS keys covered | {len(doc['actions'])} |")
    w(f"| Api methods covered (plus {len(doc['internal_api'])} internal) | "
      f"{sum(1 for v in doc['api'].values() if v)} |")
    w(f"| Methods reached by neither old UI, now given a home (★) | {len(doc['unreached_before_v1'])} |")
    for kind, label in doc["placement_kinds"].items():
        w(f"| Placement: {kind} ({label}) | {kinds.get(kind, 0)} |")
    w("")
    w("Columns: **Menu** native menu ids (payload variants in braces); **Actions** cockpit "
      "`ACTIONS` keys; **Api** methods, ★ = reached by neither old UI before v1; "
      "**Placement** as defined above.")
    w("")
    for ws in doc["workspaces"]:
        w(f"## {TITLES.get(ws, ws)} ({counts.get(ws, 0)})")
        w("")
        w("| Id | Feature | Menu | Actions | Api | New home | Placement |")
        w("|---|---|---|---|---|---|---|")
        for r in rows:
            if r["workspace"] != ws:
                continue
            api = ", ".join(f"`{m}`" + (" ★" if m in r["star_methods"] else "") for m in r["api"]) or "—"
            feature = _cell(r["feature"])
            if not r["origin"].startswith("REBUILD_PLAN section 1") or "+ U00" in r["origin"]:
                feature += " <sup>U00</sup>"
            w(f"| `{r['id']}` | {feature} | {_codes(r['menu'])} | {_codes(r['actions'])} | {api} | "
              f"{_cell(r['new_home'])} | {r['placement']}{' · unbacked' if r.get('unbacked') else ''} |")
        w("")
    w("<sup>U00</sup> marks a row added or extended in U00: a verb the cockpit or menu reaches "
      "that the plan's table named only generically or not at all.")
    w("")
    w("## Native menu → rows")
    w("")
    w("| Menu id | Title | Rows |")
    w("|---|---|---|")
    for mid, entry in doc["menu"].items():
        w(f"| `{_cell(mid)}` | {_cell(entry['title'])} | {_codes(entry['rows'])} |")
    w("")
    w("## Internal Api methods (no control by design)")
    w("")
    for name, why in doc["internal_api"].items():
        w(f"- `{name}`: {why}")
    w("")
    w("## Design elements with no Api yet")
    w("")
    w("Owner decision 2026-09-29: build the backend for every one of these, for real and "
      "with tests. Until then none may show an invented value.")
    w("")
    for gap in doc["unbacked_design_elements"]:
        w(f"- {gap}")
    w("")
    w(f"Note: {doc['unreached_note']}")
    w("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python tools/ui_inventory.py")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render(json.loads(JSON_PATH.read_text(encoding="utf-8")))
    if args.check:
        current = MD_PATH.read_text(encoding="utf-8") if MD_PATH.exists() else ""
        if current != text:
            print("docs/ui/INVENTORY.md is stale: run python tools/ui_inventory.py --write", file=sys.stderr)
            return 1
        return 0
    if args.write:
        MD_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {MD_PATH}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
