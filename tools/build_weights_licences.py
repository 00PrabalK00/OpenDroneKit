"""Assemble WEIGHTS_LICENSES.md from the model registry and docs/model_licences/*.md.

The registry's ``licence`` block on each row is the machine-readable record; the licence
page beside it holds the clauses, attribution and data notes in prose. This tool joins
the two so the document users read cannot drift from either. Run it after adding or
changing a licence block or page:

    python -m tools.build_weights_licences          # rewrite WEIGHTS_LICENSES.md
    python -m tools.build_weights_licences --check  # exit 1 if it is stale

tests/test_release_weight_urls.py fails while the document is stale.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
REGISTRY = REPO / "models" / "model_registry.json"
PAGES = REPO / "docs" / "model_licences"
OUTPUT = REPO / "WEIGHTS_LICENSES.md"

SECTIONS = [
    ("commercial", "Commercial use allowed",
     "Permissive weights (MIT, Apache-2.0, BSD). Keep the attribution notices with the weights."),
    ("copyleft", "Copyleft",
     "AGPL-3.0 weights. Commercial use is allowed, but distributing them, or running a network "
     "service on them, carries AGPL-3.0 obligations for the combined work."),
    ("non-commercial", "Non-commercial only",
     "Research, evaluation or educational use only. Do not use these weights for commercial "
     "work. Where a row also says AGPL-3.0, both notices apply; see the OWNER GATE."),
]
BADGE = {"commercial": "Commercial OK", "copyleft": "Copyleft AGPL",
         "non-commercial": "Non-commercial"}

# The InsPLAD weights arrive with Unit 5. The gate is written whether or not those rows
# have merged yet, because it is a decision the owner has to make before release.
INSPLAD_KEYS = ("powerline_insplad_detector", "powerline_insplad_condition")

HEADER = """# Model weights: licences for v0.1.0-beta

<!-- Generated by tools/build_weights_licences.py from models/model_registry.json and
docs/model_licences/*.md. Edit those, then run: python -m tools.build_weights_licences -->

OpenDroneKit's source code is MIT. **The MIT licence covers the code only.** Each set of
model weights ships under its own licence terms, inherited from the base model it was
fine-tuned from and the data it was trained on, with that licence's text
(`LICENSES/<key>.txt`) and attribution (`docs/model_licences/<key>.md`) beside it.

The rule applied: a model ships under its own terms, and is held back only if its licence
forbids redistribution outright, or if no single set of terms can satisfy its inputs.

Weights are never committed to this repository. Published weights are GitHub Release
assets of `v0.1.0-beta`, and the first-run downloader installs a file only if it hashes to
the sha256 recorded in the registry. The app shows each model's licence as a badge
(Commercial OK / Copyleft AGPL / Non-commercial) in Run Model and Prelabel.

This is an engineering record, not legal advice.
"""


def _rows() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8"))["models"]


def _assets(row: dict) -> list[tuple[str, str, str]]:
    """(asset name, sha256, bytes) for each published file of a row."""
    spec = row.get("download") or {}
    if spec.get("files"):
        return [(f["name"], f["sha256"], f"{int(f['bytes']):,}" if f.get("bytes") else "")
                for f in spec["files"]]
    if spec.get("url"):
        return [(spec["url"].rsplit("/", 1)[-1], row.get("sha256", ""), "")]
    return []


def _page(key: str) -> str:
    """A licence page with its H1 removed and its headings pushed under the key's heading."""
    path = PAGES / f"{key}.md"
    if not path.is_file():
        return f"_No licence page: `docs/model_licences/{key}.md` is missing._\n"
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    text = re.sub(r"\A# .*\n+", "", text)
    text = re.sub(r"^(#{2,4}) ", lambda m: "#" * (len(m.group(1)) + 2) + " ", text, flags=re.M)
    return text.strip() + "\n"


def _metric(row: dict) -> str:
    metric = row.get("metric")
    if isinstance(metric, dict) and metric.get("value") is not None:
        who = {"opendronekit": "measured by OpenDroneKit",
               "publisher": "publisher's figure"}.get(metric.get("measured_by", ""), "")
        return f"{metric.get('name', '')} {metric['value']} on {metric.get('split', '')} ({who})"
    return "unmeasured"


def build() -> str:
    rows = _rows()
    published = {k: r for k, r in rows.items() if r.get("download")}
    held = {k: r for k, r in rows.items()
            if (r.get("licence") or {}).get("redistribution") in {"held", "forbidden"}}

    out = [HEADER]

    out.append("## Summary\n")
    out.append("| Registry key | Badge | Weights licence | Asset | sha256 |")
    out.append("|---|---|---|---|---|")
    for key in sorted(published):
        lic = published[key].get("licence") or {}
        for name, digest, _ in _assets(published[key]):
            out.append(f"| `{key}` | {BADGE.get(lic.get('use', ''), 'none recorded')} | "
                       f"{lic.get('weights', 'none recorded')} | `{name}` | `{digest}` |")
    out.append("")

    for use, title, blurb in SECTIONS:
        keys = sorted(k for k, r in published.items() if (r.get("licence") or {}).get("use") == use)
        out.append(f"## {title}\n")
        out.append(blurb + "\n")
        if not keys:
            out.append("_None published in this release._\n")
        for key in keys:
            row = published[key]
            lic = row.get("licence") or {}
            out.append(f"### `{key}`\n")
            out.append("| Asset | Bytes | sha256 |")
            out.append("|---|---|---|")
            for name, digest, size in _assets(row):
                out.append(f"| `{name}` | {size or 'see release'} | `{digest}` |")
            out.append("")
            out.append(f"- Weights: {lic.get('weights', '')} ({lic.get('weights_url', '')})")
            if lic.get("copyleft"):
                out.append(f"- Also: {lic['copyleft']} (copyleft); see the OWNER GATE below.")
            out.append(f"- Data: {lic.get('data', '')}")
            out.append(f"- Attribution: {lic.get('attribution', '')}")
            out.append(f"- Metric on record: {_metric(row)}")
            out.append(f"- Licence text: `LICENSES/{key}.txt`; model card: "
                       f"`docs/model_cards/{key}.md`\n")
            out.append(_page(key))

    out.append("## Held back\n")
    out.append("Not published in v0.1.0-beta. Users can still run these from weights they obtain "
               "themselves; the registry rows and their sha256 checks are unchanged.\n")
    out.append("| Registry key | Clause or reason | Fix |")
    out.append("|---|---|---|")
    for key in sorted(held):
        lic = held[key].get("licence") or {}
        reason = str(lic.get("held_reason", "")).replace("|", "\\|")
        fix = ""
        if "Fix:" in reason:
            reason, fix = (part.strip() for part in reason.split("Fix:", 1))
        out.append(f"| `{key}` | {reason} | {fix} |")
    out.append("")
    for key in sorted(held):
        out.append(f"### `{key}`\n")
        out.append(_page(key))

    out.append("## OWNER GATE: AGPL-3.0 weights trained on non-commercial data\n")
    out.append("**Open decision for the owner. Confirm or reject before the release is published.**\n")
    out.append(
        "Ultralytics states that every YOLO fine-tune is AGPL-3.0 (\"All Ultralytics YOLO trained "
        "models fall under the AGPL-3.0 License by default\", https://www.ultralytics.com/license). "
        "AGPL-3.0 section 10 forbids imposing \"any further restrictions on the exercise of the "
        "rights granted or affirmed under this License\", and a non-commercial condition is such "
        "a restriction. So a YOLO fine-tune whose data or weight licence is non-commercial has "
        "no single set of terms that satisfies both. Neither licence forbids redistribution "
        "outright, so under the owner's rule these ship, flagged non-commercial, with both "
        "notices. `shared_semantic_landcover` was held for a comparable conflict (CC BY-SA vs "
        "CC BY-NC-SA); the difference is recorded here so the owner decides it explicitly.\n")
    out.append("| Registry key | Non-commercial terms | AGPL source | Status in this release |")
    out.append("|---|---|---|---|")
    insplad_terms = ("InsPLAD weights and data, CC BY-NC 3.0. Card: \"non-commercial use only "
                     "... weights are derivative works of the InsPLAD dataset\"")
    for key in INSPLAD_KEYS:
        state = ("published, flagged" if key in published else
                 "registered by Unit 5, not published" if key in rows else
                 "arrives with Unit 5 (models/U5_infrastructure_detectors)")
        out.append(f"| `{key}` | {insplad_terms} | Ultralytics YOLO11s fine-tune | {state} |")
    for key in sorted(k for k, r in rows.items() if (r.get("licence") or {}).get("copyleft")):
        lic = rows[key]["licence"]
        state = "published, flagged" if key in published else "not published"
        out.append(f"| `{key}` | {lic.get('data', '')} | {lic['copyleft']} (Ultralytics fine-tune) "
                   f"| {state} |")
    out.append("")
    out.append("If the owner says **no**: remove the `download` entries of every row above "
               "(and set `licence.redistribution` to `\"held\"` with the reason), then rerun "
               "this tool. For power lines, `powerline_ttpla_yolo11s_seg` (AGPL-3.0, Apache-2.0 "
               "data, no conflict) then remains the only model.\n")

    unlicensed = sorted(k for k, r in rows.items()
                        if r.get("status") == "installed" and not r.get("licence"))
    out.append("## Installed rows with no licence block\n")
    if unlicensed:
        out.append("These have no `licence` block, so they carry no download and no badge:\n")
        out.extend(f"- `{k}`" for k in unlicensed)
        out.append("")
    else:
        out.append("None.\n")

    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("WEIGHTS_LICENSES.md is stale: run python -m tools.build_weights_licences")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
